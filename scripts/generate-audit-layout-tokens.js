import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(
  readFileSync(new URL("src/design-system/apex.tokens.json", root), "utf8"),
);
const layout = tokens.auditLayout;
const declarations = [
  ["analyticsFilterMinWidth", "analytics-filter-min-width", "rem"],
  ["overviewTrackCompact", "overview-track-compact", "rem"],
  ["tableIdentityViewportLimit", "table-identity-viewport-limit", "vw"],
];
const uiDeclarations = [
  ["mobileThemeMaxWidth", "mobile-theme-max-width", "px"],
  ["dialogMaxHeight", "dialog-max-height", "rem"],
  ["menuMaxHeight", "menu-max-height", "rem"],
  ["menuMinWidth", "menu-min-width", "rem"],
  ["driverBadgeMinWidth", "driver-badge-min-width", "rem"],
  ["circuitImageMaxHeight", "circuit-image-max-height", "rem"],
  ["questionActionMinWidth", "question-action-min-width", "rem"],
  ["questionLabelMinWidth", "question-label-min-width", "rem"],
  ["analyticsStatMinHeight", "analytics-stat-min-height", "rem"],
  ["analyticsMetricMinHeight", "analytics-metric-min-height", "rem"],
  ["analyticsMarkerSize", "analytics-marker-size", "rem"],
  ["analyticsResultMinHeight", "analytics-result-min-height", "rem"],
  ["analyticsEmptyMinHeight", "analytics-empty-min-height", "rem"],
  ["analyticsEvidenceMinHeight", "analytics-evidence-min-height", "rem"],
  ["analyticsContextColumnWidth", "analytics-context-column-width", "rem"],
  ["analyticsWeekendMinWidth", "analytics-weekend-min-width", "rem"],
  ["analyticsWeekendMinHeight", "analytics-weekend-min-height", "rem"],
  [
    "analyticsMobileMetricMinHeight",
    "analytics-mobile-metric-min-height",
    "rem",
  ],
  ["analyticsMobileStatMinHeight", "analytics-mobile-stat-min-height", "rem"],
  [
    "analyticsComparisonControlMinHeight",
    "analytics-comparison-control-min-height",
    "px",
  ],
  ["selectionBorderWidth", "selection-border-width", "px"],
  ["metadataTracking", "metadata-tracking", "em"],
  ["pageEyebrowTracking", "page-eyebrow-tracking", "em"],
  ["statusIconGap", "status-icon-gap", "em"],
];
const positiveLength = (value, unit) => {
  const match = new RegExp(`^(\\d+(?:\\.\\d+)?)${unit}$`).exec(value);
  return match && Number.isFinite(Number(match[1])) && Number(match[1]) > 0;
};
if (
  !layout ||
  !declarations.every(([key, , unit]) => positiveLength(layout[key], unit)) ||
  !tokens.uiConsistency ||
  !uiDeclarations.every(([key, , unit]) =>
    positiveLength(tokens.uiConsistency[key], unit),
  ) ||
  !Number.isFinite(tokens.chart?.axisNameGap) ||
  tokens.chart.axisNameGap <= 0 ||
  !["width", "height", "padding"].every(
    (key) =>
      Number.isFinite(tokens.chart?.homeMiniPlot?.[key]) &&
      tokens.chart.homeMiniPlot[key] > 0,
  ) ||
  tokens.chart.homeMiniPlot.padding * 2 >=
    Math.min(
      tokens.chart.homeMiniPlot.width,
      tokens.chart.homeMiniPlot.height,
    ) ||
  !Number.isSafeInteger(layout.overviewDesktopMinWidth) ||
  layout.overviewDesktopMinWidth <= 0 ||
  !Number.isSafeInteger(tokens.breakpoints?.tablet) ||
  tokens.breakpoints.tablet <= 0 ||
  !Number.isSafeInteger(tokens.homeFidelity?.desktopMinWidth) ||
  tokens.homeFidelity.desktopMinWidth <= 0 ||
  !["action", "pageHeading", "status", "navigation", "brand"].every(
    (key) => Number.isSafeInteger(tokens.icons?.[key]) && tokens.icons[key] > 0,
  )
)
  throw new Error("Invalid audit layout tokens");

// CSS variables cannot be media conditions. Regenerate these owned aliases by
// file/token key, never by selector occurrence or edits to unrelated base CSS.
const media = [
  "analytics-density",
  "race-mobile",
  "reflow",
  "standings-context",
  "table",
  "ui-consistency",
].map((name) => [`${name}.css`, "max-width", tokens.breakpoints.tablet - 1]);
media.push(["overview-focus.css", "min-width", layout.overviewDesktopMinWidth]);
for (const identity of ["driver", "constructor"])
  media.push([
    `${identity}-identity.css`,
    "min-width",
    tokens.homeFidelity.desktopMinWidth,
  ]);
const styles = media.map(([file, condition, value]) => {
  const path = new URL(`src/design-system/${file}`, root);
  const css = readFileSync(path, "utf8");
  const pattern = new RegExp(`@media \\(${condition}: \\d+px\\)`, "g");
  if ([...css.matchAll(pattern)].length !== 1)
    throw new Error(`Invalid owned media alias: ${file}`);
  return {
    path,
    css: css.replace(pattern, `@media (${condition}: ${value}px)`),
  };
});
const css = [
  ...declarations.map(
    ([key, name]) => `  --apex-size-${name}: ${layout[key]};`,
  ),
  ...uiDeclarations.map(
    ([key, name]) => `  --apex-size-ui-${name}: ${tokens.uiConsistency[key]};`,
  ),
].join("\n");
writeFileSync(
  new URL("src/design-system/audit-layout.tokens.css", root),
  `/* Generated by scripts/generate-audit-layout-tokens.js from keyed Apex JSON. */\n:root {\n${css}\n}\n`,
);
for (const style of styles) writeFileSync(style.path, style.css);
