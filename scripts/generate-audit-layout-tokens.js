import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(
  readFileSync(new URL("src/design-system/apex.tokens.json", root), "utf8"),
);
const layout = tokens.auditLayout;
const declarations = [
  ["analyticsFilterMinWidth", "analytics-filter-min-width", "rem"],
  ["overviewTrackCompact", "overview-track-compact", "rem"],
  ["tableIdentityViewportLimit", "table-identity-viewport-limit", "vw"],
];
const positiveLength = (value, unit) => {
  const match = new RegExp(`^(\\d+(?:\\.\\d+)?)${unit}$`).exec(value);
  return match && Number.isFinite(Number(match[1])) && Number(match[1]) > 0;
};
if (
  !layout ||
  !declarations.every(([key, , unit]) => positiveLength(layout[key], unit)) ||
  !Number.isSafeInteger(layout.overviewDesktopMinWidth) ||
  layout.overviewDesktopMinWidth <= 0 ||
  !Number.isSafeInteger(tokens.breakpoints?.tablet) ||
  tokens.breakpoints.tablet <= 0 ||
  !["action", "pageHeading", "status", "navigation", "brand"].every(
    (key) => Number.isSafeInteger(tokens.icons?.[key]) && tokens.icons[key] > 0,
  )
)
  throw new Error("Invalid audit layout tokens");

// CSS variables cannot be media conditions. Regenerate these owned aliases by
// file/token key, never by selector occurrence or edits to unrelated base CSS.
const media = [
  "analytics-density",
  "race-mobile",
  "reflow",
  "standings-context",
  "table",
].map((name) => [`${name}.css`, "max-width", tokens.breakpoints.tablet - 1]);
media.push(["overview-focus.css", "min-width", layout.overviewDesktopMinWidth]);
const styles = media.map(([file, condition, value]) => {
  const path = new URL(`src/design-system/${file}`, root);
  const css = readFileSync(path, "utf8");
  const pattern = new RegExp(`@media \\(${condition}: \\d+px\\)`, "g");
  if ([...css.matchAll(pattern)].length !== 1)
    throw new Error(`Invalid owned media alias: ${file}`);
  return {
    path,
    css: css.replace(pattern, `@media (${condition}: ${value}px)`),
  };
});
const css = declarations
  .map(([key, name]) => `  --apex-size-${name}: ${layout[key]};`)
  .join("\n");
writeFileSync(
  new URL("src/design-system/audit-layout.tokens.css", root),
  `/* Generated by scripts/generate-audit-layout-tokens.js from keyed Apex JSON. */\n:root {\n${css}\n}\n`,
);
for (const style of styles) writeFileSync(style.path, style.css);
