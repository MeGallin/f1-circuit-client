import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(
  readFileSync(new URL("src/design-system/apex.tokens.json", root), "utf8"),
);
// Generate the constructor extension from keyed JSON values, without patching
// unrelated generated typography/colour CSS by selector occurrence order.
const themeCss = ["dark", "light"]
  .map((theme) => {
    const { logoTile, logoTileDark } = tokens.themes[theme];
    if (
      ![logoTile, logoTileDark].every((value) => /^#[0-9a-f]{6}$/i.test(value))
    )
      throw new Error("Invalid constructor tile colour");
    const selector =
      theme === "dark" ? ':root,\n[data-theme="dark"]' : '[data-theme="light"]';
    return `${selector} {\n  --apex-color-logo-tile: ${logoTile};\n  --apex-color-logo-tile-dark: ${logoTileDark};\n}`;
  })
  .join("\n");
writeFileSync(
  new URL("src/design-system/constructor-media.css", root),
  `/* Generated by scripts/generate-constructor-media.js from Apex constructor tokens. */
${themeCss}
`,
);
