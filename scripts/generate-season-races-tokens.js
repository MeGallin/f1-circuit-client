import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(
  readFileSync(new URL("src/design-system/apex.tokens.json", root), "utf8"),
);
const ribbon = tokens.seasonRaces;
const mobile = tokens.breakpoints?.tablet;
const lengths = ["cardWidth", "cardMinWidth", "cardMinHeight"];
const fluid = ["cardFluidWidth", "cardFluidHeight"];
const scaled = [
  "headingSize",
  "nameSize",
  "cardPadding",
  "arrowHeight",
  "statusIcon",
];
const positive = (value) => Number.isFinite(Number(value)) && Number(value) > 0;
const validFluid = (value) => {
  const match = /^(\d+(\.\d+)?)cqw$/.exec(value);
  return match && positive(match[1]);
};
const validClamp = (value) => {
  const match = /^clamp\((\d+)px, (\d+(\.\d+)?)cqw, (\d+)px\)$/.exec(value);
  return (
    match &&
    positive(match[1]) &&
    positive(match[2]) &&
    positive(match[4]) &&
    Number(match[1]) <= Number(match[4])
  );
};
if (
  !ribbon ||
  typeof ribbon !== "object" ||
  ![...lengths.map((key) => ribbon[key]), mobile].every(
    (value) => Number.isSafeInteger(value) && value > 0,
  ) ||
  ribbon.cardMinWidth > ribbon.cardWidth ||
  !fluid.every((key) => validFluid(ribbon[key])) ||
  !scaled.every((key) => validClamp(ribbon[key])) ||
  !/^[1-9]\d*ch$/.test(ribbon.footerActionLabelWidth) ||
  !/^\d+%$/.test(ribbon.latestTint) ||
  parseInt(ribbon.latestTint, 10) > 100
)
  throw new Error("Invalid season ribbon tokens");
const declarations = [
  ...lengths,
  ...fluid,
  ...scaled,
  "footerActionLabelWidth",
  "latestTint",
]
  .map((key) => {
    const name = key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
    return `  --apex-season-races-${name}: ${ribbon[key]}${lengths.includes(key) ? "px" : ""};`;
  })
  .join("\n");
writeFileSync(
  new URL("src/design-system/season-races.tokens.css", root),
  `/* Generated by scripts/generate-season-races-tokens.js from keyed Apex JSON. */
:root {
${declarations}
}
@media (max-width: ${mobile - 1}px) {
  .season-races-navigation {
    grid-template-columns: 1fr 1fr;
  }
  .season-races-list {
    grid-column: 1 / -1;
    grid-row: 1;
  }
  .season-races .season-races-arrow {
    grid-row: 2;
  }
  .season-races-arrow:last-child {
    justify-self: end;
  }
  .season-races-navigation--expanded {
    grid-template-columns: minmax(0, 1fr);
  }
  .season-races {
    padding: var(--apex-space-6);
  }
}
`,
);
